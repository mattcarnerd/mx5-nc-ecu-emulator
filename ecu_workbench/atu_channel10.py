"""Channel10 disabled-input startup subset, Rev3 11.2.26/11.3.12.

Ambiguous A/C/F reset diagrams never choose a value silently. Zero reload
wrap is an explicit experimental policy; default stops before using it.
Correction compares old E/F on each supplied Pphi tick, a declared synchronous
packet-order model, not a physical timing validation.
"""
A=0xFFFFF6C0;B=0xFFFFF6C4;C=0xFFFFF6C6;D=0xFFFFF6C8
E=0xFFFFF6CA;F=0xFFFFF6CC;G=0xFFFFF6CE
ICR=0xFFFFF6D0;OCR=0xFFFFF6D4;OCRB=0xFFFFF6D8;RLD=0xFFFFF6DA
GR=0xFFFFF6DC;H=0xFFFFF6DE;NCR=0xFFFFF6E0;TIOR=0xFFFFF6E2
TCR=0xFFFFF6E4;TCCLR=0xFFFFF6E6;TSR=0xFFFFF6E8;TIER=0xFFFFF6EA
TSTR=0xFFFFF401;PSCR4=0xFFFFF40A
WIDTHS={A:4,B:1,C:2,D:1,E:2,F:2,G:2,ICR:4,OCR:4,OCRB:1,RLD:2,
        GR:2,H:1,NCR:1,TIOR:1,TCR:1,TCCLR:2,TSR:2,TIER:2}
INITIAL={A:None,C:None,F:None,OCR:0xFFFFFFFF,OCRB:0xFF,GR:0xFFFF,NCR:0xFF}

class Channel10InitialRuntime:
    def __init__(self,atu,*,power_on):
        self.atu=atu;self.power_on=power_on;self.enabled=False
        self.regs={a:INITIAL.get(a,0) if power_on else None for a in WIDTHS}
        self.initial_fixture=None;self.zero_reload_policy=None;self.access_started=False

    def set_initial_candidates(self,values,*,zero_reload_policy=None):
        if not self.power_on or self.access_started or self.initial_fixture is not None:
            raise ValueError('Channel10 initial candidates require untouched power-reset state')
        if not isinstance(values,dict) or set(values)!={'A','C','F'} or any(type(v) is not int or v not in (0,1) for v in values.values()):
            raise ValueError('Explicit channel10 A/C/F candidates must each be integer0 or1')
        if zero_reload_policy not in (None,'experimental-wrap16'):
            raise ValueError('Unknown channel10 zero-reload policy')
        self.initial_fixture=dict(values);self.zero_reload_policy=zero_reload_policy
        for name,address in (('A',A),('C',C),('F',F)):self.regs[address]=values[name]
        self.atu.explicit_input_events+=1

    def handles(self,address):
        return any(base<=address<base+width for base,width in WIDTHS.items())

    def guard(self,address,width,operation):
        if WIDTHS.get(address)!=width:
            self.atu.fail('unsupported_access_size','Channel10 requires documented aligned byte/word/long access',address,width,operation)

    def known(self,address):
        value=self.regs[address]
        if value is None:self.atu.fail('unknown_peripheral_reset_state','Channel10 initial/retained register unknown',address,WIDTHS[address],'read')
        return value

    def read(self,address,width):
        self.guard(address,width,'read');self.access_started=True
        if self.atu.known(TSTR)&0x80 and not self.enabled:
            self.atu.fail('missing_input','Running channel10 requires explicit startup clock fixture',address,width,'read')
        return self.known(address)

    def write(self,address,width,value):
        self.guard(address,width,'write');self.access_started=True
        if address==ICR:self.atu.fail('read_only_peripheral','ICR10A is read-only',address,width,'write',value)
        if address in (TCR,TIOR,TIER,TSR) and value==0:
            # Idempotent default controls/disabled requests; dynamic flags have
            # not been generated by this guarded startup subset.
            if self.known(address)!=0:self.atu.fail('unsupported_peripheral_mode','Channel10 active control/status changes outside subset',address,width,'write',value)
        elif address in (A,C,D,E,F,G,RLD,OCR,OCRB,GR,TCCLR):
            if self.enabled or self.atu.known(TSTR)&0x80:
                self.atu.fail('unsupported_peripheral_mode','Configure channel10 data before binding/running',address,width,'write',value)
        else:self.atu.fail('unsupported_peripheral_mode','Channel10 mode/input/status operation outside startup subset',address,width,'write',value)
        self.regs[address]=value&((1<<(width*8))-1)
        self.atu.trace.append({'register':'ATU10','address':f'0x{address:08X}',
            'access':'write','width':width,'value':self.regs[address],'scope':'bounded_internal_startup'})

    def guard_start(self):
        for address in WIDTHS:self.known(address)
        if self.known(TCR)!=0 or self.known(TIOR)!=0 or self.known(TIER)!=0:
            self.atu.fail('unsupported_peripheral_mode','Channel10 startup requires disabled TI10/clear/compare requests')
        if self.known(E)>self.known(F):
            self.atu.fail('unsupported_peripheral_mode','Active channel10 correction before fixture binding outside subset')

    def prepare(self,count):
        if not self.enabled or not self.atu.known(TSTR)&0x80:return None
        # F may lag E after previous packets: that is normal correction here.
        for address in WIDTHS:self.known(address)
        if self.known(TCR) or self.known(TIOR) or self.known(TIER):
            self.atu.fail('unsupported_peripheral_mode','Channel10 input/control changes outside startup subset')
        state=dict(self.regs);pulses=corrected=0;divisor=self.atu.known(PSCR4)+1
        for offset in range(1,count+1):
            old_e,old_f=state[E],state[F]
            if old_f<old_e:
                next_f=(old_f+1)&0xFFFF
                if next_f==state[TCCLR]:
                    self.atu.fail('unsupported_peripheral_mode','Channel10 correction-clear boundary outside subset',F,2)
                state[F]=next_f;corrected+=1
            if (self.atu.phi_cycles+offset)%divisor:continue
            next_a=(state[A]+1)&0xFFFFFFFF
            if next_a==state[OCR] or next_a==0:
                self.atu.fail('unsupported_peripheral_mode','Channel10 A compare/overflow boundary outside subset',A,4)
            state[A]=next_a
            if state[C] in (0,1) and state[RLD]==0 and self.zero_reload_policy is None:
                self.atu.fail('unsupported_peripheral_mode','Channel10 zero reload/underflow behavior unspecified; no experimental policy supplied',C,2)
            if state[C]==1:
                state[C]=state[RLD];pulses+=1
                if state[E]==0xFFFF or state[G]==0xFFFF:
                    self.atu.fail('unsupported_peripheral_mode','Channel10 E/G wrap boundary outside subset',E,2)
                state[E]+=1;state[G]+=1
            else:state[C]=(state[C]-1)&0xFFFF
        return state,pulses,corrected

    def apply(self,plan):
        if plan is None:return
        self.regs,pulses,corrected=plan
        if pulses or corrected:
            event={'kind':'channel10_internal_clocks','agck1_pulses':pulses,
                'agckm_pulses':corrected,'time_unit':'supplied_Pphi_packet',
                'physical_timing_verified':False}
            self.atu.events.append(event);self.atu.events[:]=self.atu.events[-100:]
            if self.atu.event_sink:self.atu.event_sink(dict(event))
